import { hashContrasena } from '../services/password.service.js'

function fecha(diasAtras) {
  const valor = new Date()
  valor.setDate(valor.getDate() - diasAtras)
  return valor.toISOString().slice(0, 10)
}

function haceHoras(horas) {
  return new Date(Date.now() - horas * 60 * 60 * 1000).toISOString()
}

function usuarioSemilla(id, nombre, correo, usuario, rol, contrasena, estado, horas) {
  const { hash, salt } = hashContrasena(contrasena)
  return {
    id,
    nombre,
    correo,
    usuario,
    rol,
    estado,
    contrasenaHash: hash,
    contrasenaSalt: salt,
    creadoEn: haceHoras(horas + 500),
    actualizadoEn: haceHoras(horas),
  }
}

